def south_id(n):
    return {'el2': 'el1', 'd-el2': 'd-el1', 'stA': 'stC', 'd-stA': 'd-stC', 'stB': 'stD', 'd-stB': 'd-stD'}.get(n, f'{n}-s')


def build_graph():
    nodes = dict(NODES_N)
    nodes.update({south_id(n): (x, mirror_y(y)) for n, (x, y) in NODES_N.items()})
    nodes.update(NODES_MID)
    edges = list(EDGES_N)
    for a, b, t, acc in EDGES_N:
        sa = a if a in NODES_MID else south_id(a)
        sb = b if b in NODES_MID else south_id(b)
        edges.append((sa, sb, t, acc))
    edges = list(dict.fromkeys(edges))
    pois = []
    for node, cat, name, unit in POIS_N:
        pois.append((node, cat, name, unit))
        if node in SOUTH_NAMES:
            s_node, s_name, s_unit = SOUTH_NAMES[node]
        else:
            s_node, s_name, s_unit = south_id(node), name.replace('北', '南'), unit.replace('-N', '-S')
        pois.append((s_node, cat, s_name, s_unit))
    return nodes, edges, pois


# 1F <-> 2F connectors: (1F node, 2F node, type, accessible)
CONNECTORS = [
    ('1F-el2', '2F-el2', 'elevator', True), ('1F-el1', '2F-el1', 'elevator', True),
    ('1F-stA', '2F-stA', 'stairs', False), ('1F-stB', '2F-stB', 'stairs', False),
    ('1F-stC', '2F-stC', 'stairs', False), ('1F-stD', '2F-stD', 'stairs', False),
]


def main():
    nid = lambda n: f'{LEVEL}-{n}'
    nodes, edges, pois = build_graph()
    for a, b, *_ in edges:
        assert a in nodes and b in nodes, (a, b)

    units = [{'type': 'Feature', 'geometry': {'type': 'Polygon', 'coordinates': [poly]},
              'properties': {'id': nid(uid), 'level': LEVEL, 'category': cat, **({'ref': ref} if ref else {}),
                             **({'name': name} if name else {}), **extra}}
             for uid, cat, ref, name, poly, extra in UNITS]
    poi_feats = [{'type': 'Feature', 'geometry': {'type': 'Point', 'coordinates': list(nodes[node])},
                  'properties': {'id': nid(f'poi-{node}'), 'level': LEVEL, 'category': cat, 'name': name,
                                 'unit_id': nid(unit), 'nav_node': nid(node)}}
                 for node, cat, name, unit in pois]

    nav_path = f'{OUT}/nav.geojson'
    nav = json.load(open(nav_path, encoding='utf-8'))
    keep = [f for f in nav['features'] if not (
        f['properties'].get('level') == LEVEL
        or (f['properties']['kind'] == 'edge' and (f['properties']['from'].startswith(LEVEL) or f['properties']['to'].startswith(LEVEL))))]
    pos = {f['properties']['id']: f['geometry']['coordinates'] for f in keep if f['properties']['kind'] == 'node'}
    feats = keep + [{'type': 'Feature', 'geometry': {'type': 'Point', 'coordinates': list(p)},
                     'properties': {'kind': 'node', 'id': nid(n), 'level': LEVEL}} for n, p in nodes.items()]
    for a, b, typ, acc in edges:
        pa, pb = nodes[a], nodes[b]
        feats.append({'type': 'Feature', 'geometry': {'type': 'LineString', 'coordinates': [list(pa), list(pb)]},
                      'properties': {'kind': 'edge', 'from': nid(a), 'to': nid(b), 'type': typ, 'accessible': acc,
                                     'length_m': round(math.dist(pa, pb), 2)}})
        pos[nid(a)], pos[nid(b)] = list(pa), list(pb)
    for a, b, typ, acc in CONNECTORS:
        assert a in pos and b in pos, (a, b)
        # SCHEMA: elevator = fixed 15 m equivalent; stairs = 2x climb + plan distance
        length = 15.0 if typ == 'elevator' else round(2 * FLOOR_HEIGHT_M + math.dist(pos[a], pos[b]), 2)
        feats.append({'type': 'Feature', 'geometry': {'type': 'LineString', 'coordinates': [pos[a], pos[b]]},
                      'properties': {'kind': 'edge', 'from': a, 'to': b, 'type': typ, 'accessible': acc, 'length_m': length}})

    write(f'{OUT}/levels/{LEVEL}/units.geojson', fc(units))
    write(f'{OUT}/levels/{LEVEL}/pois.geojson', fc(poi_feats))
    write(nav_path, fc(feats))

    # guard: no nav edge may run through a wall (positioning carves free space along edges; see nav_wall_check.py)
    import nav_wall_check  # noqa: E402
    bad = nav_wall_check.crossings(os.path.dirname(nav_path))
    nodes_bad = nav_wall_check.node_issues(os.path.dirname(nav_path))
    for c in bad:
        print(f"  WALL CROSSING {c['edge']} at {c['at']} ({c['layer']} #{c['wall']})")
    for n in nodes_bad:
        print(f"  {n['node']} at {n['at']}: {n['issue']}")
    if bad or nodes_bad:
        raise SystemExit(f'{len(bad)} nav edge/wall crossing(s), {len(nodes_bad)} node issue(s): fix the nodes '
                         '(tools/nav_wall_check.py --png to see them)')


if __name__ == '__main__':
    main()
